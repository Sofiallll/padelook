def main():
    # Если старая БД существует, сохраняем её копию.
    if DB_PATH.exists():
        backup_path = DATA_DIR / 'padel_backup_before_rebuild.db'
        shutil.copy2(DB_PATH, backup_path)
        print(f"Резервная копия старой БД: {backup_path.name}")

    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()
    cursor.execute("PRAGMA foreign_keys = ON")

    # Удаляем старые таблицы в порядке от дочерних к родительским.
    cursor.execute("DROP TABLE IF EXISTS tariff")
    cursor.execute("DROP TABLE IF EXISTS club_service")
    cursor.execute("DROP TABLE IF EXISTS club_metric")  # старая таблица, больше не используется
    cursor.execute("DROP TABLE IF EXISTS service")
    cursor.execute("DROP TABLE IF EXISTS source")
    cursor.execute("DROP TABLE IF EXISTS club")

    cursor.execute("""
    CREATE TABLE club (
        club_id INTEGER PRIMARY KEY,
        name TEXT NOT NULL,
        website TEXT,
        address TEXT,
        metro TEXT,
        area TEXT,
        courts_count INTEGER,
        online_booking INTEGER CHECK (online_booking IN (0, 1) OR online_booking IS NULL)
    )
    """)

    cursor.execute("""
    CREATE TABLE source (
        source_id INTEGER PRIMARY KEY,
        source_name TEXT NOT NULL,
        source_type TEXT,
        url TEXT,
        collection_method TEXT,
        update_frequency TEXT
    )
    """)

    cursor.execute("""
    CREATE TABLE service (
        service_id INTEGER PRIMARY KEY,
        service_name TEXT NOT NULL,
        category TEXT
    )
    """)

    cursor.execute("""
    CREATE TABLE club_service (
        club_service_id INTEGER PRIMARY KEY,
        club_id INTEGER NOT NULL,
        service_id INTEGER NOT NULL,
        source_id INTEGER,
        checked_at TEXT NOT NULL,
        availability_status TEXT NOT NULL,
        FOREIGN KEY (club_id) REFERENCES club(club_id),
        FOREIGN KEY (service_id) REFERENCES service(service_id),
        FOREIGN KEY (source_id) REFERENCES source(source_id),
        UNIQUE (club_id, service_id, checked_at)
    )
    """)

    cursor.execute("""
    CREATE TABLE tariff (
        tariff_id INTEGER PRIMARY KEY,
        club_id INTEGER NOT NULL,
        service_id INTEGER NOT NULL,
        source_id INTEGER,
        product_type TEXT,
        days TEXT,
        start_time TEXT,
        end_time TEXT,
        price REAL,
        price_type TEXT,
        duration_minutes INTEGER,
        quantity INTEGER,
        payment_unit TEXT,
        payment_mode TEXT,
        tariff_type TEXT,
        checked_at TEXT,
        note TEXT,
        FOREIGN KEY (club_id) REFERENCES club(club_id),
        FOREIGN KEY (service_id) REFERENCES service(service_id),
        FOREIGN KEY (source_id) REFERENCES source(source_id)
    )
    """)

    cursor.executemany("""
    INSERT INTO club
    (club_id, name, website, address, metro, area, courts_count, online_booking)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    """, CLUBS)

    cursor.executemany("""
    INSERT INTO source
    (source_id, source_name, source_type, url, collection_method, update_frequency)
    VALUES (?, ?, ?, ?, ?, ?)
    """, SOURCES)

    cursor.executemany("""
    INSERT INTO service (service_id, service_name, category)
    VALUES (?, ?, ?)
    """, SERVICES)

    cursor.executemany("""
    INSERT INTO club_service
    (club_service_id, club_id, service_id, source_id, checked_at, availability_status)
    VALUES (?, ?, ?, ?, ?, ?)
    """, CLUB_SERVICES)

    cursor.executemany("""
    INSERT INTO tariff (
        tariff_id, club_id, service_id, source_id, product_type, days,
        start_time, end_time, price, price_type, duration_minutes,
        quantity, payment_unit, payment_mode, tariff_type, checked_at, note
    )
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, TARIFFS)

    conn.commit()

    cursor.execute("PRAGMA foreign_key_check")
    fk_errors = cursor.fetchall()

    print("\nБаза данных создана:", DB_PATH.name)
    for table in ("club", "source", "service", "club_service", "tariff"):
        cursor.execute(f"SELECT COUNT(*) FROM {table}")
        print(f"{table}: {cursor.fetchone()[0]} строк")

    if fk_errors:
        print("ВНИМАНИЕ: найдены ошибки внешних ключей:", fk_errors)
    else:
        print("Проверка внешних ключей пройдена.")

    print("\nДля тестирования парсера оставлены без тарифов клубы, кроме ID 1 и 2.")
    print("Например, Паделград (club_id=5) есть в CLUB, но его тарифы не заполнены.")

    conn.close()


if __name__ == "__main__":
    main()
